_language = "zh"
_sources = {value: key for key, value in EN_MESSAGES.items()}


class Message(str):
    """Retain the source template so status text can be rendered again on a switch."""
    def __new__(cls, template, parameters):
        # Keep nested messages, but never retain an exception and its worker frames.
        parameters = {key: (value.args[0] if value.args and isinstance(value.args[0], Message) else str(value))
                      if isinstance(value, BaseException) else value for key, value in parameters.items()}
        translated = EN_MESSAGES.get(template, template) if _language == "en" else template
        values = {key: tr(value) if isinstance(value, Message) else value for key, value in parameters.items()}
        instance = super().__new__(cls, translated.format(**values) if values else translated)
        instance.template, instance.parameters = template, parameters
        return instance

    def __add__(self, other):
        return Message("{left}{right}", {"left": self, "right": other})

    def __radd__(self, other):
        return Message("{left}{right}", {"left": other, "right": self})


def tr(message, **parameters):
    if isinstance(message, Message):
        return Message(message.template, message.parameters)
    return Message(str(message), parameters)


def join_text(separator, messages):
    parts = list(messages)
    template = "{separator}".join("{item" + str(index) + "}" for index in range(len(parts)))
    return Message(template, {"separator": separator, **{"item" + str(index): item for index, item in enumerate(parts)}})


def source_text(text):
    return _sources.get(str(text), str(text))


def ui_text(text):
    """Translate a widget caption from either language without touching user data."""
    return tr(source_text(text))


def language():
    return _language


